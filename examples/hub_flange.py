"""范例：驱动轮轮毂零件图（A3 1:1）—— SW 出投影，AutoCAD 整理标注，全程不碰键鼠。

零件：法兰 Φ120×12 + 轮毂 Φ60，总长 52；孔 Φ30H7 带 8 mm 键槽；6×Φ9 均布在 Φ95；R2 圆角；C1 倒角。
用法：python hub_flange.py <hub.SLDPRT> <输出目录>
      零件可用 SolidWorks MCP 建（solidworks_* 工具），也可用 sw_part.py。

步骤：
 1) sw_views：国标 A3 模板、1:1，建圆视图（*前视）+ 过轴线的 A-A 全剖，导出 DWG/DXF/PDF
 2) sw_views.dump_dxf：打印各视图的粗线坐标、圆、圆弧 —— 下面标注用的坐标全是从这里抄的
 3) sw2acad.Sheet：AutoCAD 里分层、换字体、标尺寸/粗糙度/基准/形位公差、填标题栏、出 PDF
改零件后，第 2 步的坐标要重新看一遍。
"""
import os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "scripts"))
import sw_views as V
from sw2acad import Sheet, P

part, outdir = sys.argv[1], sys.argv[2]
base = os.path.join(outdir, "hub_sw")

# ---------------------------------------------------------------- 1. SolidWorks 投影
sw = V.connect()
drw = V.new_drawing(sw, "A3")
v1 = V.model_view(drw, part, "*前视", (300, 175))           # 圆视图（右）
sv = V.section(drw, v1, (0, 75), (0, -75), (140, 175))       # 竖直剖切线穿过圆心；剖视图放左边
V.finish(drw, [v1, sv])
V.export(drw, base)

# ---------------------------------------------------------------- 2. 取坐标
VIEWS = [(100, 100, 178, 250), (225, 95, 375, 256)]          # 两个视图框（比 finish 打印的外框略大，含中心线）
V.dump_dxf(base + ".DXF", VIEWS)
# 读到的关键坐标：
#   剖视图: 轴线 y=175；轮毂端面 x=114，法兰前面 x=154，法兰后面 x=166；法兰外缘 y=115/235，
#           轮毂外圆 y=145/205；孔 y=160/190，键槽顶 y=193.3；R2 圆心 (152,207)
#   圆视图: 圆心 (300,175)；孔 R15；键槽宽 8（x=296..304）顶 y=193.3；6 个 R4.5 孔在 R47.5 上，起始 30°

# ---------------------------------------------------------------- 3. AutoCAD 整理 + 标注
with Sheet(base + ".DWG", os.path.join(outdir, "hub_gb.dwg"), views=VIEWS, own_frame=False) as s:   # 沿用 SW 模板图框，标题栏用 title() 填
    s.circle((300, 175), 47.5)                                   # 螺栓孔分布圆（中心线层）
    # 剖视图
    s.dimlin((165, 235), (165, 115), (205, 175), 90, "%%C120")
    s.dimlin((115, 205), (115, 145), (100, 175), 90, "%%C60")
    s.dimlin((114, 146), (166, 116), (140, 96))                  # 总长 52
    s.dimlin((154, 116), (166, 116), (160, 105))                 # 法兰厚 12
    r2 = s.dimrad((152, 207), 2, 315, 10, "R2")
    r2.TextPosition = P(147, 224)                                # 文字挪出剖面线区
    s.rough((135, 160), 1.6)                                     # 孔表面（符号尖端落在轮廓线上）
    s.rough((122, 205), 3.2)                                     # 轮毂外圆
    s.rough_leader((166, 165), (172, 182), 3.2)                  # 竖直面用指引线式
    s.datum((166, 140), "A", direction=(1, 0))                   # 基准 A：法兰安装面（避开螺栓孔）
    s.gtol("f", "0.03", "A", (66, 125), [(114, 125)])            # 端面对 A 的平行度，箭头落在端面延长线
    # 圆视图
    s.dimdia((300, 175), 15, 300, 30, "%%C30H7")
    s.dimdia((300, 175), 47.5, 15, 18, "%%C95")
    s.dimdia((258.86, 151.25), 4.5, 225, 30, "6×%%C9 EQS")
    s.dimlin((296, 193.3), (304, 193.3), (300, 208), 0, "8JS9")
    s.dimlin((300, 160), (296, 193.3), (281, 176), 90, "33.3")   # t = d + t2 = 30 + 3.3
    # 其余粗糙度、标题栏、技术要求
    s.layer("文字"); t = s.ms.AddText("其余", P(330, 72), 5); t.StyleName = "HZ"
    s.rough((350, 70), 6.3)
    s.title({"“图样名称”": "驱动轮轮毂", "“图样代号”": "SL-02-05", "普通碳钢": "45"})
    s.notes(["1. 未注倒角 C1。", "2. 调质处理 220~250HBW。", "3. 键槽尺寸按 GB/T 1095—2003。"])
